#!/usr/bin/env node
// Assembles .design-sync/ds-entry.css from app/globals.css, then compiles it with the
// Tailwind CLI into .design-sync/.cache/ds-compiled.css (the converter's cfg.cssEntry).
//
// Run this BEFORE package-build.mjs on every sync - it is the step that keeps the uploaded
// stylesheet in step with the site's real theme.
//
// Two things it does that a plain copy of globals.css would not:
//   1. Re-declares every @theme token as a plain :root custom property. `@theme inline`
//      makes Tailwind paste values directly into utilities, so 93 of the 99 tokens have no
//      var() form in compiled output - a design agent writing var(--color-fit) would get
//      nothing. Re-declaring restores that idiom alongside the utility classes.
//   2. Safelists the brand utility families via @source inline(). The design agent writes
//      markup this repo has never contained, so content scanning alone would omit any
//      brand utility the site does not already happen to use.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const SRC = 'app/globals.css';
const ENTRY = '.design-sync/ds-entry.css';
const OUT = '.design-sync/.cache/ds-compiled.css';
const CLI = '.ds-sync/node_modules/@tailwindcss/cli/dist/index.mjs';

const css = readFileSync(SRC, 'utf8');
const cut = (a, b) => css.slice(css.indexOf(a), css.indexOf(b));
const themeBlock = cut('@theme inline', '/* ─── Brand palette');
const roles = cut(':root {', '/* ─── Cookie consent');          // :root + .dark
const keyframes = css.slice(css.indexOf('@keyframes marquee'), css.indexOf('@layer base'));
const themeBody = themeBlock.slice(themeBlock.indexOf('{') + 1, themeBlock.lastIndexOf('}')).trim();

const names = (pre) => [...new Set([...themeBlock.matchAll(new RegExp(`--${pre}-([\\w-]+)\\s*:`, 'g'))].map((m) => m[1]))].sort();
const roleNames = [...new Set([...roles.slice(0, roles.indexOf('.dark')).matchAll(/--([\w-]+)\s*:/g)].map((m) => m[1]))].filter((n) => n !== 'radius');
const colors = [...new Set([...names('color'), ...roleNames])].sort();
const br = (a) => `{${a.join(',')}}`;

// Only bg/text/border are crossed with the full colour set. Crossing
// from/via/to/shadow/ring/fill/stroke as well made the design app's theme detector
// register ~200 utility classes as selectable "themes" (From Accent, Shadow Ink, Via
// Transparent...), burying the one real theme, `.dark`. Gradients here are authored as
// inline styles from config/gradients.ts, not as utilities, so nothing needs them.
const safelist = [
  `{bg,text,border}-${br(colors)}`,
  `{hover:,focus:,active:,group-hover:,dark:,focus-visible:}{bg,text,border}-${br(colors)}`,
  `{bg,text,border}-${br(colors)}/{5,10,15,20,25,30,40,50,60,70,75,80,85,90,95}`,
  `text-${br(names('text'))}`,
  `{sm:,md:,lg:,xl:}text-${br(names('text'))}`,
  `leading-${br(names('leading'))}`,
  `tracking-${br(names('tracking'))}`,
  `max-w-${br(names('container'))}`,
  `ease-${br(names('ease'))}`,
  `{p,px,py,pt,pb,pl,pr,m,mx,my,mt,mb,ml,mr,gap,gap-x,gap-y,w,h,min-w,min-h,top,bottom,left,right,inset}-spine`,
  `rounded-{sm,md,lg,xl,2xl}`,
  `font-{sans,mono}`,
].map((s) => `@source inline("${s}");`).join('\n');

writeFileSync(ENTRY, `/* GENERATED by .design-sync/build-css.mjs from ${SRC} - do not hand-edit.
   Site plumbing (lenis smooth-scroll, vanilla-cookieconsent #cc-main) is excluded;
   neither is part of the design language. */
@import "tailwindcss" source(none);
@source "../app";
@source "../config";
/* The reference cards live outside app/, so their classes need scanning too - without
   these two the palette and type-ramp previews render unstyled. Scoped to the two exact
   paths rather than the whole directory, so .cache/ (which holds the compiled CSS this
   step writes) is never scanned back into itself. */
@source "../.design-sync/ds-components.tsx";
@source "../.design-sync/previews";

${safelist}

@custom-variant dark (&:is(.dark *));

${themeBlock}

/* next/font/google injects these two on <body> in the app. The design bundle has no
   Next.js, so they are bound here to the self-hosted families in fonts/fonts.css. */
:root {
  --font-montserrat: "Montserrat", ui-sans-serif, system-ui, sans-serif;
  --font-plex-mono: "IBM Plex Mono", ui-monospace, SFMono-Regular, Menlo, monospace;
}

/* Every @theme token again as a plain custom property - see header note 1. */
:root {
${themeBody}
}

${roles}

${keyframes}
@layer base {
  * { @apply border-border outline-ring/50; }
  body { @apply bg-background text-foreground font-sans; }
}
`);

mkdirSync('.design-sync/.cache', { recursive: true });
execFileSync(process.execPath, [CLI, '-i', ENTRY, '-o', OUT], { stdio: 'inherit' });
const out = readFileSync(OUT, 'utf8');
const declared = [...new Set([...themeBlock.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]))];
const emitted = new Set([...out.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]));
const missing = declared.filter((d) => !emitted.has(d));
if (missing.length) { console.error(`✗ ${missing.length} token(s) still unreachable as var(): ${missing.join(', ')}`); process.exit(1); }
console.error(`✓ ${OUT}: ${(out.length / 1024).toFixed(0)} KB, all ${declared.length} @theme tokens reachable as var()`);
